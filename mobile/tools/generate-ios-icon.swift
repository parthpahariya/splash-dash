// The app icon for both platforms: a ship's silhouette sailing past a setting sun, with a pirate
// pennant at the masthead. Colours come from the game theme (Clay.kt / Theme in TheLastSailApp.swift).
//
// Rebuild from the repository root with: swift mobile/tools/generate-ios-icon.swift
// It writes the iOS 1024 px PNG and the Android adaptive-icon vectors from the same shapes, so the
// two icons always match. Shapes use Android's 108-unit adaptive-icon grid. Everything important
// sits inside the 66-unit safe zone; iOS and pre-Oreo Android show the central 72 units, which is
// what a circular Android mask shows.

struct Shape {
    let color: String  // #RRGGBB
    let path: String  // absolute M, L, Q, C and Z commands only
    /// Part of the one-colour silhouette Android 13+ uses for themed icons.
    var monochrome = false
}

let background = "#0E3440"  // Clay.deep

func circle(_ cx: Double, _ cy: Double, _ r: Double) -> String {
    let k = 0.5523 * r
    func f(_ v: Double) -> String { String(format: "%.2f", v) }
    return "M\(f(cx)),\(f(cy - r)) C\(f(cx + k)),\(f(cy - r)) \(f(cx + r)),\(f(cy - k)) \(f(cx + r)),\(f(cy)) "
        + "C\(f(cx + r)),\(f(cy + k)) \(f(cx + k)),\(f(cy + r)) \(f(cx)),\(f(cy + r)) "
        + "C\(f(cx - k)),\(f(cy + r)) \(f(cx - r)),\(f(cy + k)) \(f(cx - r)),\(f(cy)) "
        + "C\(f(cx - r)),\(f(cy - k)) \(f(cx - k)),\(f(cy - r)) \(f(cx)),\(f(cy - r)) Z"
}
/// A rolling wave, wide enough for the feature graphic, with its crests at `y`, filled down to the bottom edge.
func sea(_ y: Double, phase: Double = 0) -> String {
    var d = "M-56,\(y)"
    var x = -56.0 + phase
    while x < 164 {
        d += " Q\(x + 9),\(y - 4.5) \(x + 18),\(y) Q\(x + 27),\(y + 4.5) \(x + 36),\(y)"
        x += 36
    }
    return d + " L\(x),116 L-56,116 Z"
}

let shapes: [Shape] = [
    Shape(color: "#17485A", path: circle(54, 53, 29)),  // evening glow (Clay.surface)
    Shape(color: "#FFC94D", path: circle(54, 53, 22)),  // the sun (Clay.gold)
    Shape(color: "#5FE3C0", path: sea(69)),  // wave crest (Clay.mint)
    Shape(color: "#17485A", path: sea(71.5)),
    Shape(color: "#0B2530", path: sea(81, phase: -18)),  // deep water (Clay.ink)
    // The ship, in ink silhouette against the sun.
    Shape(color: "#0B2530", path: "M30,64 L78,64 L72,73 Q54,76 36,73 Z", monochrome: true),  // hull
    Shape(color: "#0B2530", path: "M53,30 L55,30 L55,64 L53,64 Z", monochrome: true),  // mast
    Shape(color: "#0B2530", path: "M57,33 Q72,44 75,60 L57,60 Z", monochrome: true),  // mainsail
    Shape(color: "#0B2530", path: "M51,37 Q40,47 35,60 L51,60 Z", monochrome: true),  // foresail
    Shape(color: "#FF5D73", path: "M55,27 L63,30 L55,33 Z", monochrome: true),  // pirate pennant (Clay.danger)
    Shape(color: "#0B2530", path: "M53,26 L55,26 L55,32 L53,32 Z", monochrome: true),  // masthead
]

// MARK: Android

let root = "mobile/android/app/src/main/res"
func vector(_ body: String) -> String {
    """
    <!-- Generated by mobile/tools/generate-ios-icon.swift; edit the shapes there and rerun it. -->
    <vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    \(body)</vector>

    """
}
func paths(_ list: [Shape], color: (Shape) -> String = { "#FF" + $0.color.dropFirst() }, indent: String = "    ") -> String {
    list.map { "\(indent)<path android:fillColor=\"\(color($0))\" android:pathData=\"\($0.path)\" />\n" }.joined()
}
func write(_ text: String, _ path: String) {
    try! text.write(toFile: path, atomically: true, encoding: .utf8)
}
// Adaptive icon (Android 8+): the shapes are already sized for the safe zone.
write(vector(paths(shapes)), "\(root)/drawable/ic_launcher_foreground.xml")
// Themed icon (Android 13+): the system tints this one-colour layer, so it is the ship alone.
write(vector(paths(shapes.filter { $0.monochrome }, color: { _ in "#FFFFFFFF" })), "\(root)/drawable/ic_launcher_monochrome.xml")
// Legacy icon (Android 7): no mask, so zoom in to the same central 72 units the adaptive icon shows.
let legacy = vector(
    "    <path android:fillColor=\"\(background)\" android:pathData=\"M0,0L108,0L108,108L0,108Z\" />\n"
        + "    <group android:scaleX=\"1.5\" android:scaleY=\"1.5\" android:pivotX=\"54\" android:pivotY=\"54\">\n"
        + paths(shapes, indent: "        ") + "    </group>\n")
write(legacy, "\(root)/mipmap/ic_launcher.xml")
write(legacy, "\(root)/mipmap/ic_launcher_round.xml")
write(
    """
    <resources>
        <color name="ic_launcher_background">\(background)</color>
    </resources>

    """, "\(root)/values/colors.xml")

// MARK: Images

/// Draws the shapes into a `width` × `height` PNG showing the world rectangle `view`.
/// `extra` draws on top in pixel coordinates (origin top left).
func render(
    _ width: Int, _ height: Int, view: CGRect, to path: String, extra: (CGContext) -> Void = { _ in }
) {
    let c = CGContext(
        data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: width * 4,
        space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
    // Flip to Android's top-left origin.
    c.translateBy(x: 0, y: Double(height))
    c.scaleBy(x: 1, y: -1)
    c.saveGState()
    c.scaleBy(x: Double(width) / view.width, y: Double(height) / view.height)
    c.translateBy(x: -view.minX, y: -view.minY)
    func fill(_ hex: String) {
        let v = UInt32(hex.dropFirst(), radix: 16)!
        c.setFillColor(
            CGColor(
                srgbRed: Double((v >> 16) & 255) / 255, green: Double((v >> 8) & 255) / 255,
                blue: Double(v & 255) / 255, alpha: 1))
    }
    fill(background)
    c.fill(view.insetBy(dx: -10, dy: -10))
    for shape in shapes {
        c.addPath(cgPath(shape.path))
        fill(shape.color)
        c.fillPath()
    }
    c.restoreGState()
    extra(c)
    let destination = CGImageDestinationCreateWithURL(
        URL(fileURLWithPath: path) as CFURL, "public.png" as CFString, 1, nil)!
    CGImageDestinationAddImage(destination, c.makeImage()!, nil)
    guard CGImageDestinationFinalize(destination) else { fatalError("Could not write \(path)") }
}
func cgPath(_ d: String) -> CGPath {
    let p = CGMutablePath()
    let scanner = Scanner(string: d)
    scanner.charactersToBeSkipped = CharacterSet(charactersIn: " ,")
    func point() -> CGPoint { CGPoint(x: scanner.scanDouble()!, y: scanner.scanDouble()!) }
    while let command = scanner.scanCharacter() {
        switch command {
        case "M": p.move(to: point())
        case "L": p.addLine(to: point())
        case "Q": let control = point(); p.addQuadCurve(to: point(), control: control)
        case "C": let c1 = point(), c2 = point(); p.addCurve(to: point(), control1: c1, control2: c2)
        case "Z": p.closeSubpath()
        default: fatalError("Unsupported path command \(command)")
        }
    }
    return p
}

// The icons show the central 72 units (18…90), as a circular Android mask does.
let iconView = CGRect(x: 18, y: 18, width: 72, height: 72)
render(1024, 1024, view: iconView, to: "mobile/ios/TheLastSail/Assets.xcassets/AppIcon.appiconset/AppIcon.png")

// Google Play store listing: the 512 px hi-res icon and the 1024 × 500 feature graphic.
let listing = "mobile/android/listing"
render(512, 512, view: iconView, to: "\(listing)/icon-512.png")
// The ship sits right of centre with the title on the left. Play may crop the edges, so the
// title stays well inside them.
let featureHeight = 62.0
let featureWidth = featureHeight * 1024 / 500
render(
    1024, 500, view: CGRect(x: 54 - featureWidth * 0.72, y: 22, width: featureWidth, height: featureHeight),
    to: "\(listing)/feature-graphic.png"
) { c in
    func line(_ text: String, size: CGFloat, color: NSColor, kern: CGFloat, y: CGFloat) {
        let base = NSFont.systemFont(ofSize: size, weight: .black)
        let font = base.fontDescriptor.withDesign(.rounded).flatMap { NSFont(descriptor: $0, size: size) } ?? base
        let attributed = NSAttributedString(
            string: text, attributes: [.font: font, .foregroundColor: color, .kern: kern])
        let ctLine = CTLineCreateWithAttributedString(attributed)
        c.saveGState()
        // Text draws with a bottom-left origin, so undo the flip for it.
        c.translateBy(x: 96, y: y)
        c.scaleBy(x: 1, y: -1)
        c.textPosition = .zero
        CTLineDraw(ctLine, c)
        c.restoreGState()
    }
    let cream = NSColor(srgbRed: 1, green: 0xF6 / 255.0, blue: 0xE0 / 255.0, alpha: 1)
    let gold = NSColor(srgbRed: 1, green: 0xC9 / 255.0, blue: 0x4D / 255.0, alpha: 1)
    line("THE LAST", size: 64, color: cream, kern: 2, y: 228)
    line("SAIL", size: 112, color: gold, kern: 4, y: 330)
}
